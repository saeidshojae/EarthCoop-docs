function escapeHtml(value) {
  return String(value ?? '')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
}

function renderRelated(related, { mode = 'static' } = {}) {
  return related.map(([title, route]) => {
    const href = mode === 'spa' ? `#/${route}` : `/guides/${route}/`;
    return `<a href="${href}"><span>مطالعه بعدی</span><strong>${escapeHtml(title)} ←</strong></a>`;
  }).join('');
}

function renderStaticGuide(guideRecord) {
  return `<div class="page" data-guide-revision="${GUIDE_AUDIT_REVISION}"><div class="breadcrumbs"><a href="/">خانه</a><i></i><span>${escapeHtml(guideRecord.category)}</span></div><div class="article-layout"><article><header class="article-head"><span class="eyebrow">${escapeHtml(guideRecord.category)}</span><h1>${escapeHtml(guideRecord.title)}</h1><p>${escapeHtml(guideRecord.description)}</p><div class="meta-row"><span class="badge concept">ممیزی‌شده</span><span class="badge review">زبان مبنا: فارسی</span></div><div class="content-identity"><div class="identity-item"><span>نوع محتوا</span><strong>${escapeHtml(guideRecord.category)}</strong></div><div class="identity-item"><span>نسخه صفحه</span><strong><bdi dir="ltr">${GUIDE_AUDIT_REVISION}</bdi></strong></div><div class="identity-item"><span>سطح اعتبار</span><strong>راهنمای ممیزی‌شده</strong></div><div class="identity-item"><span>بازبینی</span><strong><bdi dir="ltr">${guideRecord.reviewedAt}</bdi></strong></div></div><div class="source-note"><strong>مبنای فعلی:</strong> ${escapeHtml(guideRecord.sourceNote)}</div></header><div class="article-body">${guideRecord.bodyHtml}<div class="section-title"><div><span class="eyebrow">ادامه مسیر</span><h2>مطالب مرتبط</h2></div></div><div class="related">${renderRelated(guideRecord.related)}</div></div></article><aside class="toc"><strong>در این صفحه</strong>${[...guideRecord.bodyHtml.matchAll(/<h2 id="([^"]+)">([^<]+)<\/h2>/g)].map((match) => `<a href="#${match[1]}" data-anchor>${match[2]}</a>`).join('')}</aside></div></div>`;
}

function browserOverridesSource() {
  const rows = AUDITED_GUIDES_FA.map((item) => {
    return `${JSON.stringify(item.route)}:article(${JSON.stringify(item.title)},${JSON.stringify(item.category)},${JSON.stringify(item.description)},${JSON.stringify(item.state)},${JSON.stringify(item.bodyHtml)},${JSON.stringify(item.related)})`;
  }).join(',\n  ');
  return `Object.assign(pages,{\n  ${rows}\n});\nconst AUDITED_GUIDE_REVISION=${JSON.stringify(GUIDE_AUDIT_REVISION)};\n`;
}

export function patchRecoveredGuideAppSource(source) {
  let output = String(source ?? '');
  if (output.includes(`const AUDITED_GUIDE_REVISION=${JSON.stringify(GUIDE_AUDIT_REVISION)}`)) return output;
  const marker = 'function tocFrom(html)';
  if (!output.includes(marker)) throw new Error('Recovered article override patch point changed');

  const oldSource = "const source=state==='verified'?'تصمیم صریح بنیان‌گذار و معماری تثبیت‌شده':'معماری هدف؛ نیازمند تطبیق با مخزن و سند مرجع';";
  if (!output.includes(oldSource)) throw new Error('Recovered article source-note patch point changed');
  output = output.replace(oldSource, "const source=state==='verified'?'اسناد رسمی نافذ و شواهد ممیزی‌شده مخزن EarthCoop':'محتوای در حال ممیزی؛ نیازمند تطبیق با سند و محصول';");
  return output.replace(marker, `${browserOverridesSource()}\n${marker}`);
}

function metadataRecord(item) {
  return `{ inventoryId:'page.${item.route}', route:'${item.route}', title:${JSON.stringify(item.title)}, description:${JSON.stringify(item.description)}, contentClass:'guide', status:'unofficial_explanation', source:${JSON.stringify(item.sourceNote)}, sourceType:'editorial', authority:'تحریریه مرکز دانش بر پایه ممیزی مخزن و اسناد رسمی', version:'1.0.0', reviewedAt:'2026-10-02' }`;
}

export function patchRecoveredGuideMetadataSource(source) {
  let output = String(source ?? '');
  for (const item of AUDITED_GUIDES_FA) {
    const pattern = new RegExp(`\\{\\s*inventoryId:'page\\.${item.route}',[^\\n]+\\}`);
    if (!pattern.test(output)) throw new Error(`Recovered guide metadata record changed for ${item.route}`);
    output = output.replace(pattern, metadataRecord(item));
  }
  return output;
}

export function patchRecoveredGuideHtml(source, item) {
  const input = String(source ?? '');
  if (input.includes(`data-guide-revision="${GUIDE_AUDIT_REVISION}"`)) return input;
  const pattern = /<main id="app"[^>]*>[\s\S]*?<\/main>/;
  if (!pattern.test(input)) throw new Error(`Recovered guide main patch point changed for ${item.route}`);
  return input.replace(pattern, `<main id="app" tabindex="-1" aria-live="polite" aria-atomic="true">${renderStaticGuide(item)}</main>`);
}

export async function applyRecoveredGuideContent({ outDir }) {
  if (!outDir) throw new TypeError('outDir is required');

  const appPath = path.join(outDir, 'app.js');
  await writeFile(appPath, patchRecoveredGuideAppSource(await readFile(appPath, 'utf8')));

  const metadataPath = path.join(outDir, 'src', 'content', 'pages.fa.js');
  await writeFile(metadataPath, patchRecoveredGuideMetadataSource(await readFile(metadataPath, 'utf8')));

  for (const item of AUDITED_GUIDES_FA) {
    const guidePath = path.join(outDir, 'guides', item.route, 'index.html');
    await writeFile(guidePath, patchRecoveredGuideHtml(await readFile(guidePath, 'utf8'), item));
  }
}
